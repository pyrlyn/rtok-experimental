#!/usr/bin/env python3
"""Regenerate Rust models from openapi/*.yaml with openapi-generator.

One generator for every agent contract. Only the models are kept; they land in
src/skills/api/ and are committed so a plain `cargo build` needs no Java.

Usage: python3 tools/gen_openapi.py [--check]
"""
import argparse
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATOR_VERSION = "7.26.0"
# spec -> (output dir, Rust module path that replaces the generator's `crate::models`)
SPECS = {"skills.yaml": (ROOT / "src" / "skills" / "api", "crate::skills::api")}
HEADER = (
    "// Generated by openapi-generator from openapi/{spec}. Do not edit;\n"
    "// run `python3 tools/gen_openapi.py`.\n"
)


def generate(spec: str, out: Path, module: str) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [
            "npx", "-y", "@openapitools/openapi-generator-cli@2", "generate",
            "-g", "rust", "-i", str(ROOT / "openapi" / spec), "-o", tmp,
            "--global-property", "models,modelDocs=false,modelTests=false",
            "--additional-properties", "packageName=skills_api,avoidBoxedModels=true",
        ]
        env = {"OPENAPI_GENERATOR_VERSION": GENERATOR_VERSION}
        subprocess.run(cmd, check=True, cwd=tmp, env={**os.environ, **env}, stdout=subprocess.DEVNULL)
        models = Path(tmp) / "src" / "models"
        out.mkdir(parents=True, exist_ok=True)
        for old in out.glob("*.rs"):
            old.unlink()
        names = []
        for src in sorted(models.glob("*.rs")):
            if src.name == "mod.rs":
                continue
            text = src.read_text().replace("use crate::models;", f"use {module} as models;")
            (out / src.name).write_text(HEADER.format(spec=spec) + text)
            names.append(src.stem)
        lines = [HEADER.format(spec=spec), "//! Models of the OpenAPI contract.\n\n"]
        for n in names:
            lines.append(f"mod {n};\npub use {n}::*;\n")
        (out / "mod.rs").write_text("".join(lines))
        # Same layout `cargo fmt` gives the committed files, so --check stays stable.
        subprocess.run(["rustfmt", "--edition", "2024", *map(str, out.glob("*.rs"))], check=True)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed models are stale")
    args = ap.parse_args()
    for spec, (out, module) in SPECS.items():
        if args.check:
            with tempfile.TemporaryDirectory() as tmp:
                generate(spec, Path(tmp), module)
                diff = filecmp.dircmp(tmp, out)
                if diff.diff_files or diff.left_only or diff.right_only:
                    print(f"{out} is stale; run tools/gen_openapi.py", file=sys.stderr)
                    return 1
        else:
            generate(spec, out, module)
    return 0


if __name__ == "__main__":
    sys.exit(main())
